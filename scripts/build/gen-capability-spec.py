#!/usr/bin/env python3
"""Generate FlightDeck.Capability.Spec from the official SysAdmin API spec.

Sources (never edited by this script):
  docs/sysadmin-api-v2.json  - operations and the privilege each one declares in its summary
  docs/api-coverage.md       - the FlightDeck domain each operation belongs to

Constitution III: the capability map is derived, never hand-coded. This script fails loudly if
the two sources disagree (unassigned, duplicated or miscounted operations).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "docs" / "sysadmin-api-v2.json"
COVERAGE = ROOT / "docs" / "api-coverage.md"
OUT = ROOT / "backend" / "cls" / "FlightDeck" / "Capability" / "Spec.cls"

# Section number in docs/api-coverage.md -> domain id and expected operation count.
DOMAINS = {
    0: ("shell", 5),
    1: ("web-apps", 8),
    2: ("permissions", 31),
    3: ("security", 89),
    4: ("tasks", 24),
    5: ("system", 102),
    6: ("logs", 14),
}
# POST operations that only read (list/view), so they are not mutations.
NON_MUTATING_POSTS = {
    "/v2/security/audit/records",
    "/v2/journal/file/records",
    "/v2/database-dir/info",
}
PRIVILEGE_PREFIX = re.compile(r"^\((%Admin_\w+:U(?: or %Admin_\w+:U)*)\)\s*")
HTTP_METHODS = ("get", "put", "post", "delete", "patch")


def fail(message):
    print(f"gen-capability-spec: {message}", file=sys.stderr)
    sys.exit(1)


def resolve_params(spec, params):
    out = []
    for p in params:
        if "$ref" in p:
            p = spec["components"]["parameters"][p["$ref"].split("/")[-1]]
        out.append(p)
    return out


def load_operations():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    operations = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in HTTP_METHODS:
                continue
            params = resolve_params(spec, item.get("parameters", []) + op.get("parameters", []))
            summary = op.get("summary", "")
            match = PRIVILEGE_PREFIX.match(summary)
            requires = match.group(1).split(" or ") if match else []
            clean = summary[match.end():] if match else summary
            op_id = f"{method.upper()} {path}"
            operations[op_id] = {
                "operationId": op_id,
                "method": method.upper(),
                "path": path,
                "summary": clean.strip(),
                "requires": requires,
                "mutating": method != "get" and path not in NON_MUTATING_POSTS,
                "hasFilter": any(p.get("name") == "filter" and p.get("in") == "query" for p in params),
                "requiredParams": sorted(p["name"] for p in params if p.get("required")),
            }
    return operations


def load_domains():
    assignment = {}
    section = None
    row = re.compile(r"^\|\s*(GET|PUT|POST|DELETE|PATCH)\s*\|\s*`([^`]+)`\s*\|")
    for line in COVERAGE.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^## (\d+)\.", line)
        if heading:
            section = int(heading.group(1))
            continue
        m = row.match(line)
        if m and section is not None:
            method, path = m.group(1), m.group(2)
            if section not in DOMAINS:
                fail(f"unknown coverage section {section}")
            op_id = f"{method} {path}"
            if op_id in assignment:
                fail(f"operation assigned twice in api-coverage.md: {op_id}")
            assignment[op_id] = DOMAINS[section][0]
    return assignment


def main():
    operations = load_operations()
    domains = load_domains()
    missing = sorted(set(operations) - set(domains))
    extra = sorted(set(domains) - set(operations))
    if missing:
        fail(f"{len(missing)} spec operations have no domain: {missing[:5]}")
    if extra:
        fail(f"{len(extra)} coverage rows are not in the spec: {extra[:5]}")
    counts = {}
    for op_id, op in operations.items():
        op["domain"] = domains[op_id]
        counts[op["domain"]] = counts.get(op["domain"], 0) + 1
    for _, (domain, expected) in DOMAINS.items():
        if counts.get(domain, 0) != expected:
            fail(f"domain {domain} has {counts.get(domain, 0)} operations, expected {expected}")
    ordered = [operations[k] for k in sorted(operations, key=lambda k: (operations[k]["path"], operations[k]["method"]))]
    payload = json.dumps(ordered, indent=1, ensure_ascii=True)
    cls = (
        "/// Generated by scripts/build/gen-capability-spec.py from docs/sysadmin-api-v2.json and\n"
        "/// docs/api-coverage.md. Do not edit by hand.\n"
        "Class FlightDeck.Capability.Spec [ Abstract ]\n"
        "{\n\n"
        f"Parameter OPERATIONCOUNT = {len(ordered)};\n\n"
        "/// Every official operation: operationId, method, path, domain, summary, requires, mutating, hasFilter,\n/// requiredParams.\n"
        "XData Operations [ MimeType = application/json ]\n"
        "{\n"
        f"{payload}\n"
        "}\n\n"
        "/// Returns the operations as a %DynamicArray.\n"
        "ClassMethod Operations() As %DynamicArray\n"
        "{\n"
        "\tset xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_\"||Operations\")\n"
        "\tquit ##class(%DynamicAbstractObject).%FromJSON(xdata.Data)\n"
        "}\n\n"
        "}\n"
    )
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(cls, encoding="utf-8", newline="\n")
    print(f"gen-capability-spec: wrote {len(ordered)} operations to {target.relative_to(ROOT) if target.is_relative_to(ROOT) else target}")
    print("gen-capability-spec: " + ", ".join(f"{d} {counts[d]}" for d, _ in DOMAINS.values()))


if __name__ == "__main__":
    main()
