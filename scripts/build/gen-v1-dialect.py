#!/usr/bin/env python3
"""Generate FlightDeck.Admin.V1Routes: the SysAdmin API v1 translation table, keyed by v2 operationId.

Sources:
  verification/v1-api-2026.1.json   same-shape routes (identical method and path under /v1),
                                     measured against a live IRIS 2026.1 instance
  scripts/build/v1-translations.json the 28 different-shape translations, discovered live and
                                     verified by effect (FlightDeck.Test.V1Translations); the
                                     operations answered by a v1-only native provider; and the
                                     operations deliberately withheld, with their reasons

Constitution I (dialect note): translation is keyed by v2 operationId and lives in one layer.
Constitution III: nothing about privileges is read from v1; the capability map stays on the v2 spec.
Fails if an operation is both same-shape and translated, or unknown to the v2 spec.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "verification" / "v1-api-2026.1.json"
TRANSLATIONS = ROOT / "scripts" / "build" / "v1-translations.json"
SPEC = ROOT / "docs" / "sysadmin-api-v2.json"
OUT = ROOT / "backend" / "cls" / "FlightDeck" / "Admin" / "V1Routes.cls"


def fail(message):
    print(f"gen-v1-dialect: {message}", file=sys.stderr)
    sys.exit(1)


def main():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    v2ops = {f"{m.upper()} {p}" for p, item in spec["paths"].items() for m in item if m in ("get", "put", "post", "delete", "patch")}
    report = json.loads(REPORT.read_text(encoding="utf-8"))["coverageAgainstV2"]
    source = json.loads(TRANSLATIONS.read_text(encoding="utf-8"))
    translations = source["translations"]
    native = source.get("native", {})
    withheld = source.get("withheld", {})
    reasons = source.get("reasons", {})

    table = {}
    for op_id, (method, path) in report["sameShapeRoutes"].items():
        if op_id not in v2ops:
            fail(f"same-shape operation not in v2 spec: {op_id}")
        table[op_id] = {"method": method, "path": path, "unversioned": False, "body": {"rule": "passthrough"}}
    for op_id, entry in translations.items():
        if op_id not in v2ops:
            fail(f"translated operation not in v2 spec: {op_id}")
        if op_id in table:
            fail(f"operation is both same-shape and translated: {op_id}")
        table[op_id] = {"method": entry["method"], "path": entry["path"], "unversioned": bool(entry.get("unversioned")), "body": entry["body"]}

    for op_id, provider in native.items():
        if op_id not in v2ops:
            fail(f"native operation not in v2 spec: {op_id}")
        if op_id in table:
            fail(f"operation has a v1 route and a native provider: {op_id}")
        table[op_id] = {"native": provider}
    withheld_out = {}
    for op_id, key in withheld.items():
        if op_id not in v2ops:
            fail(f"withheld operation not in v2 spec: {op_id}")
        if op_id in table:
            fail(f"withheld operation is available: {op_id}")
        if key not in reasons:
            fail(f"withheld operation has an unknown reason key: {op_id} -> {key}")
        withheld_out[op_id] = reasons[key]

    absent = sorted(v2ops - set(table))
    payload = json.dumps(dict(sorted(table.items())), indent=1, ensure_ascii=True)
    withheld_payload = json.dumps(dict(sorted(withheld_out.items())), indent=1, ensure_ascii=True)
    cls = (
        "/// Generated by scripts/build/gen-v1-dialect.py from verification/v1-api-2026.1.json and\n"
        "/// scripts/build/v1-translations.json. Do not edit by hand.\n"
        f"/// {len(table)} v2 operations are available on the v1 dialect ({len(native)} through a native provider);\n"
        f"/// {len(absent)} are unavailable, {len(withheld_out)} of them withheld with a stated reason.\n"
        "Class FlightDeck.Admin.V1Routes [ Abstract ]\n"
        "{\n\n"
        f"Parameter TRANSLATEDCOUNT = {len(table)};\n\n"
        "XData Routes [ MimeType = application/json ]\n"
        "{\n"
        f"{payload}\n"
        "}\n\n"
        "/// Reasons appended to the version message for operations deliberately left unavailable.\n"
        "XData Withheld [ MimeType = application/json ]\n"
        "{\n"
        f"{withheld_payload}\n"
        "}\n\n"
        "/// Withheld reasons as a %DynamicObject keyed by v2 operationId. Cached per process.\n"
        "ClassMethod Withheld() As %DynamicObject\n"
        "{\n"
        "\tif $isobject($get(%FlightDeckV1Withheld)) quit %FlightDeckV1Withheld\n"
        "\tset xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_\"||Withheld\")\n"
        "\tset %FlightDeckV1Withheld = ##class(%DynamicAbstractObject).%FromJSON(xdata.Data)\n"
        "\tquit %FlightDeckV1Withheld\n"
        "}\n\n"
        "/// The table as a %DynamicObject keyed by v2 operationId. Cached per process.\n"
        "ClassMethod Table() As %DynamicObject\n"
        "{\n"
        "\tif $isobject($get(%FlightDeckV1Routes)) quit %FlightDeckV1Routes\n"
        "\tset xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_\"||Routes\")\n"
        "\tset %FlightDeckV1Routes = ##class(%DynamicAbstractObject).%FromJSON(xdata.Data)\n"
        "\tquit %FlightDeckV1Routes\n"
        "}\n\n"
        "}\n"
    )
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    target.write_text(cls, encoding="utf-8", newline="\n")
    print(f"gen-v1-dialect: {len(table)} available ({len(translations)} different shape, {len(native)} native), {len(absent)} absent ({len(withheld_out)} withheld) -> {target}")


if __name__ == "__main__":
    main()
