#!/usr/bin/env python3
"""Generate FlightDeck.API.OpenAPI from the feature contracts.

Sources, merged in order (later features add paths and schemas; a duplicate is an error):
  specs/001-foundation-shell/contracts/flightdeck-api.openapi.json        base document
  specs/002-webapps-explorer-mutations/contracts/flightdeck-api-002.openapi.json
  specs/003-permissions-security/contracts/flightdeck-api-003.openapi.json
  specs/004-tasks-system/contracts/flightdeck-api-004.openapi.json

A later contract may refine an operation an earlier one defined (feature 003 extends the entity
links query with provider parameters). That is allowed only when the operation declares
"x-refines": true, so an accidental duplicate is still an error.

The merged document is served verbatim at GET /api/flightdeck/v1/openapi.json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "specs" / "001-foundation-shell" / "contracts" / "flightdeck-api.openapi.json"
ADDITIONS = [
    ROOT / "specs" / "002-webapps-explorer-mutations" / "contracts" / "flightdeck-api-002.openapi.json",
    ROOT / "specs" / "003-permissions-security" / "contracts" / "flightdeck-api-003.openapi.json",
    ROOT / "specs" / "004-tasks-system" / "contracts" / "flightdeck-api-004.openapi.json",
]
BASE_REF = "flightdeck-api.openapi.json#/components/schemas/"


def fail(message):
    print(f"gen-openapi-cls: {message}", file=sys.stderr)
    sys.exit(1)


def local_refs(node):
    """Rewrites references to the base contract file into local references."""
    if isinstance(node, dict):
        return {k: (v.replace(BASE_REF, "#/components/schemas/") if k == "$ref" and isinstance(v, str) else local_refs(v)) for k, v in node.items()}
    if isinstance(node, list):
        return [local_refs(v) for v in node]
    return node


def contracts_merge():
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    for path in ADDITIONS:
        extra = local_refs(json.loads(path.read_text(encoding="utf-8")))
        for route, item in extra.get("paths", {}).items():
            if route not in doc["paths"]:
                doc["paths"][route] = item
                continue
            for method, operation in item.items():
                if method in doc["paths"][route] and not operation.get("x-refines"):
                    fail(f"duplicate operation {method.upper()} {route} in {path.name} (add x-refines to replace it on purpose)")
                doc["paths"][route][method] = {k: v for k, v in operation.items() if k != "x-refines"}
        schemas = doc.setdefault("components", {}).setdefault("schemas", {})
        for name, schema in extra.get("components", {}).get("schemas", {}).items():
            if name in schemas:
                fail(f"duplicate schema {name} in {path.name}")
            schemas[name] = schema
        doc["info"]["version"] = extra["info"]["version"]
    return doc
OUT = ROOT / "backend" / "cls" / "FlightDeck" / "API" / "OpenAPI.cls"


def main():
    doc = contracts_merge()
    payload = json.dumps(doc, indent=1, ensure_ascii=True)
    cls = (
        "/// Generated by scripts/build/gen-openapi-cls.py from the feature contracts\n"
        "/// (specs/001-foundation-shell, 002-webapps-explorer-mutations, 003-permissions-security\n"
        "/// and 004-tasks-system).\n"
        "/// Do not edit by hand.\n"
        "Class FlightDeck.API.OpenAPI Extends %RegisteredObject\n"
        "{\n\n"
        "XData Document [ MimeType = application/json ]\n"
        "{\n"
        f"{payload}\n"
        "}\n\n"
        "/// The OpenAPI document as a %DynamicObject.\n"
        "ClassMethod Document() As %DynamicObject\n"
        "{\n"
        "\tset xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_\"||Document\")\n"
        "\tquit ##class(%DynamicAbstractObject).%FromJSON(xdata.Data)\n"
        "}\n\n"
        "/// GET /v1/openapi.json\n"
        "ClassMethod Get() As %Status\n"
        "{\n"
        "\tquit ##class(FlightDeck.API.Response).WriteJSON(..Document())\n"
        "}\n\n"
        "}\n"
    )
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(cls, encoding="utf-8", newline="\n")
    print(f"gen-openapi-cls: wrote {target}")


if __name__ == "__main__":
    main()
