#!/usr/bin/env python3
"""Generate FlightDeck.API.OpenAPI from specs/001-foundation-shell/contracts/flightdeck-api.openapi.json.

The contract file is the single source; the class serves it verbatim at GET /api/flightdeck/v1/openapi.json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "specs" / "001-foundation-shell" / "contracts" / "flightdeck-api.openapi.json"
OUT = ROOT / "backend" / "cls" / "FlightDeck" / "API" / "OpenAPI.cls"


def main():
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    payload = json.dumps(doc, indent=1, ensure_ascii=True)
    cls = (
        "/// Generated by scripts/build/gen-openapi-cls.py from\n"
        "/// specs/001-foundation-shell/contracts/flightdeck-api.openapi.json. Do not edit by hand.\n"
        "Class FlightDeck.API.OpenAPI Extends %RegisteredObject\n"
        "{\n\n"
        "XData Document [ MimeType = application/json ]\n"
        "{\n"
        f"{payload}\n"
        "}\n\n"
        "/// The OpenAPI document as a %DynamicObject.\n"
        "ClassMethod Document() As %DynamicObject\n"
        "{\n"
        "\tset xdata = ##class(%Dictionary.CompiledXData).%OpenId($classname()_\"||Document\")\n"
        "\tquit ##class(%DynamicAbstractObject).%FromJSON(xdata.Data)\n"
        "}\n\n"
        "/// GET /v1/openapi.json\n"
        "ClassMethod Get() As %Status\n"
        "{\n"
        "\tquit ##class(FlightDeck.API.Response).WriteJSON(..Document())\n"
        "}\n\n"
        "}\n"
    )
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(cls, encoding="utf-8", newline="\n")
    print(f"gen-openapi-cls: wrote {target}")


if __name__ == "__main__":
    main()
